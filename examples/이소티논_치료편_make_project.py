def main(pptx):
    from pptx import Presentation
    n = len(Presentation(pptx).slides)
    cards = {str(k): v[2] for k, v in CARDS.items() if v[2]}
    # 카드 뒤에 그 문장에 맞는 장면 사진을 흐리고 어둡게 깐다 (2026-11-28 사용자: 고급감, 논문·체크리스트·파트·경고 카드는 까만 바탕)
    import os
    for k, spec in cards.items():
        bg = f"deliverables/이소티논_치료편/card_bg/card{k}.jpg"
        if os.path.exists(bg):
            spec["bg"] = bg
    slide_at = {str(k): ([v[0], v[1]] if v[1] else v[0]) for k, v in CARDS.items()}
    plan = {
        "title": "이소티논 부작용 치료", "hooks": [], "keywords": [], "skip": [], "cut": [],
        "speed": [{"from": 0, "to": 63, "rate": 1.25}],  # 대본: 세 부분 모두 1.25배속
        "chapters": [{"from": 0, "label": "이소티논 부작용 치료"}, {"from": 10, "label": "확인과 조정"},
                     {"from": 14, "label": "장벽"}, {"from": 25, "label": "염증"}, {"from": 38, "label": "혈관"},
                     {"from": 47, "label": "정리"}],
        "progress": {"labels": ["확인", "장벽", "염증", "혈관"], "chapters": [1, 2, 3, 4]},
        "hook_text": "이소티논 먹고 붉어졌다면\n**치료 순서**는?",
        "fix": FIX, "slide_at": slide_at,
        "slide_skip": sorted(set(range(1, n + 1)) - set(CARDS)), "slide_hide": HIDE,
        "interviews": INTERVIEWS,
    }
    broll = [{"at": a, "offset": o, "asset": f, "mode": "full", "keep": True} for a, o, f in BROLL]
    for name, obj in (("cards", cards), ("plan", plan), ("broll", broll)):
        with open(f"examples/이소티논_치료편.{name}.json", "w", encoding="utf-8") as fp:
            json.dump(obj, fp, ensure_ascii=False, indent=1)
    print(len(cards), "cards,", len(CARDS), "slides used,", len(plan["slide_skip"]), "skipped")


if __name__ == "__main__":
    main(sys.argv[1])
